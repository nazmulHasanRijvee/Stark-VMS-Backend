ALTER TABLE vehicles DROP CONSTRAINT ck_vehicles_status;

UPDATE vehicles
SET status = 'Maintenance'
WHERE status = 'In Service';

ALTER TABLE vehicles
    ADD CONSTRAINT ck_vehicles_status
        CHECK (status IN ('Active', 'Inactive', 'Maintenance'));

CREATE TABLE vehicle_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    document_type VARCHAR(40) NOT NULL,
    display_filename VARCHAR(255) NOT NULL,
    storage_object_key VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    expiry_date DATE,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vehicle_documents_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicles (id) ON DELETE RESTRICT,
    CONSTRAINT uq_vehicle_documents_storage_key UNIQUE (storage_object_key),
    CONSTRAINT ck_vehicle_documents_type CHECK (document_type IN
        ('Registration', 'Tax Token', 'Insurance', 'Fitness Certificate', 'Other')),
    CONSTRAINT ck_vehicle_documents_file_size CHECK (file_size_bytes BETWEEN 1 AND 10485760)
);

CREATE INDEX ix_vehicle_documents_vehicle_upload
    ON vehicle_documents (vehicle_id, uploaded_at DESC, id DESC);
CREATE INDEX ix_vehicle_documents_vehicle_type_upload
    ON vehicle_documents (vehicle_id, document_type, uploaded_at DESC, id DESC);
CREATE INDEX ix_vehicle_documents_expiry
    ON vehicle_documents (expiry_date);

CREATE TABLE vehicle_maintenance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    maintenance_date DATE NOT NULL,
    maintenance_type VARCHAR(128) NOT NULL,
    cost NUMERIC(12, 2) NOT NULL,
    workshop VARCHAR(128) NOT NULL,
    notes VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vehicle_maintenance_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicles (id) ON DELETE CASCADE,
    CONSTRAINT ck_vehicle_maintenance_cost CHECK (cost >= 0)
);

CREATE INDEX ix_vehicle_maintenance_vehicle_date
    ON vehicle_maintenance_records (vehicle_id, maintenance_date DESC, id DESC);
CREATE INDEX ix_vehicle_maintenance_date
    ON vehicle_maintenance_records (maintenance_date);
