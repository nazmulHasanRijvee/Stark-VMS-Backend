CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT ck_app_users_email_lowercase CHECK (email = LOWER(email))
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(64) NOT NULL,
    company_name VARCHAR(128) NOT NULL,
    vehicle_type VARCHAR(64) NOT NULL,
    brand VARCHAR(64) NOT NULL,
    model VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_vehicles_vehicle_number UNIQUE (vehicle_number),
    CONSTRAINT ck_vehicles_status CHECK (status IN ('Active', 'In Service', 'Inactive')),
    CONSTRAINT ck_vehicles_number_canonical CHECK (vehicle_number = UPPER(TRIM(vehicle_number)))
);
