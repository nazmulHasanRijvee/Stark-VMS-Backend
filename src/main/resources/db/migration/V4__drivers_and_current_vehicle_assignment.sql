CREATE TABLE drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    license_number VARCHAR(64) NOT NULL,
    license_expiry DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_drivers_license_number UNIQUE (license_number),
    CONSTRAINT ck_drivers_name CHECK (name = TRIM(name) AND LENGTH(name) BETWEEN 1 AND 120),
    CONSTRAINT ck_drivers_phone CHECK (phone = TRIM(phone) AND LENGTH(phone) BETWEEN 1 AND 32),
    CONSTRAINT ck_drivers_license_canonical CHECK (
        license_number = UPPER(TRIM(license_number)) AND LENGTH(license_number) BETWEEN 1 AND 64
    ),
    CONSTRAINT ck_drivers_status CHECK (status IN ('Active', 'Inactive'))
);

CREATE INDEX ix_drivers_name ON drivers (name);
CREATE INDEX ix_drivers_phone ON drivers (phone);
CREATE INDEX ix_drivers_status_name ON drivers (status, name);
CREATE INDEX ix_drivers_license_expiry ON drivers (license_expiry);

